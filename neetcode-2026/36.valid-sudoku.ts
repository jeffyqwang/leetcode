/*
 * 【問題(日本語)】36. 有効な数独(Valid Sudoku)
 * 9 x 9 の数独盤面が有効かどうかを判定してください。以下のルールに従って、すでに埋められている数字のみを検証すれば十分です。数字 1-9 は各行に1回ずつ、各列に1回ずつ、そして太線で区切られた各 3x3 のブロック内に1回ずつしか現れてはいけません。
 * 制約:board.length == 9、board[i].length == 9、board[i][j] は 1-9 の数字または '.'
 * 例1:入力 board = 
[["5","3",".",".","7",".",".",".","."]
,["6",".",".","1","9","5",".",".","."]
,[".","9","8",".",".",".",".","6","."]
,["8",".",".",".","6",".",".",".","3"]
,["4",".",".","8",".","3",".",".","1"]
,["7",".",".",".","2",".",".",".","6"]
,[".","6",".",".",".",".","2","8","."]
,[".",".",".","4","1","9",".",".","5"]
,[".",".",".",".","8",".",".","7","9"]] → 出力 true
 * 例2:入力 board = 
[["8","3",".",".","7",".",".",".","."]
,["6",".",".","1","9","5",".",".","."]
,[".","9","8",".",".",".",".","6","."]
,["8",".",".",".","6",".",".",".","3"]
,["4",".",".","8",".","3",".",".","1"]
,["7",".",".",".","2",".",".",".","6"]
,[".","6",".",".",".",".","2","8","."]
,[".",".",".","4","1","9",".",".","5"]
,[".",".",".",".","8",".",".","7","9"]] → 出力 false
 *   説明:1行目の最初の数字が 5 から 8 に変わっている点を除き、他のマスは例1と同じですが、左上の 3x3 ブロック内に 8 が2つあるため、この数独は無効です。
 *
 * 【用語】
 * 数独(すうどく)数独 / 盤面(ばんめん)棋盘/盘面 / 有効(ゆうこう)有效
 * 行(ぎょう)行 / 列(れつ)列 / ブロック(block)宫(3x3 区块)
 * 太線(ふとせん)粗线 / 空白マス(くうはくます)空白格 / 埋める(うめる)填入
 * 判定する(はんていする)判断
 */

