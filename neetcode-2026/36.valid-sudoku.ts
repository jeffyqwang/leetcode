// @lc code=start
function isValidSudoku(board: string[][]): boolean {
  let box: string[][] = new Array(9),
    label = true;
  for (let i = 0; i < board.length && label; i++) {
    const collectionX: string[] = [];
    const collectionY: string[] = [];
    for (let j = 0; j < board[i].length && label; j++) {
      const elementX = board[i][j];
      const elementY = board[j][i];
      if (collectionX.includes(elementX)) {
        label = false;
      } else {
        elementX !== '.' && collectionX.push(elementX);
      }
      if (collectionY.includes(elementY)) {
        label = false;
      } else {
        elementY !== '.' && collectionY.push(elementY);
      }
      const boxNo = Math.floor(i / 3) * 3 + Math.floor(j / 3);
      if (!box[boxNo]) box[boxNo] = [];
      if (box[boxNo].includes(elementX)) {
        label = false;
      } else {
        elementX !== '.' && box[boxNo].push(elementX);
      }
    }
  }
  return label;
}
